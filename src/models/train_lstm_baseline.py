"""
Train temporal baseline models on sequence data generated by csvtonpy.py.

Expected input files in --data-dir, for example:
  X_train_ratio0p6_T10_S1.npy
  y_train_ratio0p6_T10_S1.npy
  X_val_ratio0p6_T10_S1.npy
  y_val_ratio0p6_T10_S1.npy
  X_test_ratio0p6_T10_S1.npy
  y_test_ratio0p6_T10_S1.npy

Default models:
  - LSTM (default is unidirectional in this modified version)
  - GRU
  - lightweight TCN

Main changes in this modified version:
  1) Support --runs N independent train/validation/test runs.
     Each run uses a different seed, trains from scratch, selects the best checkpoint
     by validation macro-F1, and then evaluates on the test set.
     This is the correct basis for reporting mean ± standard deviation.
  2) LSTM is unidirectional by default. Use --bidirectional only if you explicitly
     want a bidirectional LSTM/GRU.

Example:
  python train_temporal_baselines.py --model lstm
  python train_temporal_baselines_unified.py --model lstm --runs 12
  python train_temporal_baselines_unified.py --model all --epochs 50 --runs 12
  python train_temporal_baselines_unified.py --suffix ratio0p6_T10_S1 --model gru
"""

