def compute_class_weights(y_train, num_classes, device):
    counts = np.bincount(y_train, minlength=num_classes).astype(np.float32)
    counts[counts == 0] = 1.0
    weights = counts.sum() / (num_classes * counts)
    return torch.tensor(weights, dtype=torch.float32, device=device)


def run_one_epoch(model, loader, criterion, optimizer, device, train=True):
    model.train(train)
    total_loss = 0.0
    total_count = 0

    for X, y in loader:
        X = X.to(device)
        y = y.to(device)

        if train:
            optimizer.zero_grad(set_to_none=True)

        with torch.set_grad_enabled(train):
            logits = model(X)
            loss = criterion(logits, y)
            if train:
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
                optimizer.step()

        batch_size = X.size(0)
        total_loss += float(loss.item()) * batch_size
        total_count += batch_size

    return total_loss / max(total_count, 1)


@torch.no_grad()
def predict(model, loader, device):
    model.eval()
    y_true = []
    y_pred = []
    y_prob = []

    for X, y in loader:
        X = X.to(device)
        logits = model(X)
        prob = torch.softmax(logits, dim=1)
        pred = torch.argmax(prob, dim=1)

        y_true.append(y.cpu().numpy())
        y_pred.append(pred.cpu().numpy())
        y_prob.append(prob.cpu().numpy())

    return np.concatenate(y_true), np.concatenate(y_pred), np.concatenate(y_prob)


def metrics_dict(y_true, y_pred):
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
        "weighted_f1": f1_score(y_true, y_pred, average="weighted", zero_division=0),
    }


def save_eval_outputs(out_dir, split_name, y_true, y_pred, y_prob, labels, model_name):
    ensure_dir(out_dir)

    report = classification_report(
        y_true,
        y_pred,
        labels=list(range(len(labels))),
        target_names=labels,
        output_dict=True,
        zero_division=0,
    )
    pd.DataFrame(report).transpose().to_csv(os.path.join(out_dir, f"{model_name}_{split_name}_classification_report.csv"))

    cm = confusion_matrix(y_true, y_pred, labels=list(range(len(labels))))
    cm_df = pd.DataFrame(cm, index=labels, columns=labels)
    cm_df.to_csv(os.path.join(out_dir, f"{model_name}_{split_name}_confusion_matrix.csv"))

    pred_df = pd.DataFrame({
        "y_true_id": y_true,
        "y_pred_id": y_pred,
        "y_true": [labels[i] for i in y_true],
        "y_pred": [labels[i] for i in y_pred],
    })
    for i, label in enumerate(labels):
        pred_df[f"prob_{label}"] = y_prob[:, i]
    pred_df.to_csv(os.path.join(out_dir, f"{model_name}_{split_name}_predictions.csv"), index=False)


def aggregate_runs(summary_df, out_dir):
    metric_cols = [
        "val_accuracy",
        "val_balanced_accuracy",
        "val_macro_f1",
        "val_weighted_f1",
        "test_accuracy",
        "test_balanced_accuracy",
        "test_macro_f1",
        "test_weighted_f1",
    ]
    metric_cols = [metric for metric in metric_cols if metric in summary_df.columns]
    rows = []
    for model_name, group in summary_df.groupby("model"):
        for metric in metric_cols:
            values = group[metric].astype(float)
            rows.append({
                "model": model_name,
                "metric": metric,
                "mean": values.mean(),
                "std": values.std(ddof=1),
                "n": values.count(),
            })
    aggregate_df = pd.DataFrame(rows)
    aggregate_df.to_csv(os.path.join(out_dir, f"{summary_df['model'].iloc[0]}_aggregate_metrics_mean_std.csv"), index=False)
    return aggregate_df


def train_model(model_name, X_train, y_train, X_val, y_val, X_test, y_test, labels, args, run_dir, run_idx, run_seed):
    set_seed(run_seed)
    X_train_run, X_val_run, X_test_run, order_seeds = apply_temporal_order(
        X_train, X_val, X_test, args.temporal_order, run_seed
    )
    device = torch.device(args.device if args.device else ("cuda" if torch.cuda.is_available() else "cpu"))
    print(f"\n==============================")
    print(f"[*] Training {model_name.upper()} | run={run_idx}/{args.runs} | seed={run_seed} | device={device}")
    print(f"==============================")

    input_dim = X_train_run.shape[-1]
    num_classes = len(labels)

    model = create_model(model_name, input_dim, num_classes, args).to(device)

    train_loader = DataLoader(
        SequenceDataset(X_train_run, y_train),
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda"),
    )
    val_loader = DataLoader(
        SequenceDataset(X_val_run, y_val),
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda"),
    )
    test_loader = None
    if not args.validation_only:
        test_loader = DataLoader(
            SequenceDataset(X_test_run, y_test),
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=(device.type == "cuda"),
        )

    class_weights = compute_class_weights(y_train, num_classes, device) if args.class_weight else None
    if class_weights is not None:
        print("[*] Using balanced class weights:")
        for label, w in zip(labels, class_weights.detach().cpu().numpy().tolist()):
            print(f"    {label}: {w:.4f}")

    criterion = nn.CrossEntropyLoss(weight=class_weights)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="max", factor=0.5, patience=max(2, args.patience // 2)
    )

    model_dir = os.path.join(run_dir, f"run_{run_idx:02d}_seed{run_seed}")
    ensure_dir(model_dir)
    with open(os.path.join(model_dir, f"{model_name}_label_mapping.json"), "w", encoding="utf-8") as f:
        json.dump({"label_to_id": {label: i for i, label in enumerate(labels)},
                   "id_to_label": {i: label for i, label in enumerate(labels)}}, f, ensure_ascii=False, indent=2)
    run_config = vars(args).copy()
    run_config.update({
        "model": model_name,
        "run_idx": int(run_idx),
        "run_seed": int(run_seed),
        "temporal_order_seeds": order_seeds,
    })
    with open(os.path.join(model_dir, f"{model_name}_run_config.json"), "w", encoding="utf-8") as f:
        json.dump(run_config, f, ensure_ascii=False, indent=2)
    best_path = os.path.join(model_dir, f"{model_name}_best.pt")

    best_val_macro_f1 = -1.0
    best_epoch = -1
    patience_counter = 0
    history = []

    for epoch in range(1, args.epochs + 1):
        train_loss = run_one_epoch(model, train_loader, criterion, optimizer, device, train=True)
        val_loss = run_one_epoch(model, val_loader, criterion, optimizer, device, train=False)
        yv_true, yv_pred, _ = predict(model, val_loader, device)
        val_metrics = metrics_dict(yv_true, yv_pred)
        val_macro_f1 = val_metrics["macro_f1"]
        scheduler.step(val_macro_f1)

        current_lr = optimizer.param_groups[0]["lr"]
        row = {
            "epoch": epoch,
            "train_loss": train_loss,
            "val_loss": val_loss,
            "lr": current_lr,
            **{f"val_{k}": v for k, v in val_metrics.items()},
        }
        history.append(row)

        print(
            f"Epoch {epoch:03d} | "
            f"train_loss={train_loss:.4f} | val_loss={val_loss:.4f} | "
            f"val_acc={val_metrics['accuracy']:.4f} | "
            f"val_macro_f1={val_macro_f1:.4f} | lr={current_lr:.2e}"
        )

        if val_macro_f1 > best_val_macro_f1 + 1e-6:
            best_val_macro_f1 = val_macro_f1
            best_epoch = epoch
            patience_counter = 0
            torch.save(
                {
                    "model_name": model_name,
                    "model_state_dict": model.state_dict(),
                    "input_dim": input_dim,
                    "num_classes": num_classes,
                    "labels": labels,
                    "args": vars(args),
                    "best_epoch": int(best_epoch),
                    "best_val_macro_f1": float(best_val_macro_f1),
                },
                best_path,
            )
        else:
            patience_counter += 1
            if patience_counter >= args.patience:
                print(f"[*] Early stopping triggered at epoch {epoch}. Best epoch={best_epoch}.")
                break

    pd.DataFrame(history).to_csv(os.path.join(model_dir, f"{model_name}_training_history.csv"), index=False)

    # Load best model before final evaluation.
    checkpoint = torch.load(best_path, map_location=device, weights_only=False)
    model.load_state_dict(checkpoint["model_state_dict"])

    yv_true, yv_pred, yv_prob = predict(model, val_loader, device)
    val_metrics = metrics_dict(yv_true, yv_pred)
    save_eval_outputs(model_dir, "val", yv_true, yv_pred, yv_prob, labels, model_name)

    final_row = {
        "model": model_name,
        "run": int(run_idx),
        "seed": int(run_seed),
        "best_epoch": int(best_epoch),
        "best_val_macro_f1": float(best_val_macro_f1),
        **{f"val_{k}": v for k, v in val_metrics.items()},
        "model_path": best_path,
        "result_dir": model_dir,
    }
    if not args.validation_only:
        yt_true, yt_pred, yt_prob = predict(model, test_loader, device)
        test_metrics = metrics_dict(yt_true, yt_pred)
        save_eval_outputs(model_dir, "test", yt_true, yt_pred, yt_prob, labels, model_name)
        final_row.update({f"test_{k}": v for k, v in test_metrics.items()})

    with open(os.path.join(model_dir, f"{model_name}_metrics.json"), "w", encoding="utf-8") as f:
        json.dump(final_row, f, ensure_ascii=False, indent=2)

    print(f"\n[+] {model_name.upper()} final metrics:")
    print(f"    Val  macro-F1: {val_metrics['macro_f1']:.4f}, acc: {val_metrics['accuracy']:.4f}")
    if not args.validation_only:
        print(f"    Test macro-F1: {test_metrics['macro_f1']:.4f}, acc: {test_metrics['accuracy']:.4f}")
    print(f"    Saved to: {model_dir}")

    return final_row


def main():
    parser = argparse.ArgumentParser(description="Train temporal baseline models on csvtonpy sequence data.")
    parser.add_argument("--data-dir", type=str, default="model_input", help="Directory containing X/y npy files.")
    parser.add_argument("--suffix", type=str, default="auto", help="File suffix after X_train_, e.g. ratio0p6_T10_S1.")
    parser.add_argument("--out-dir", type=str, default="lstm_results", help="Output directory.")
    parser.add_argument("--model", type=str, default="lstm", choices=["lstm", "gru", "tcn", "all"], help="Model to train.")
    parser.add_argument("--runs", type=int, default=1, help="Number of independent train/val/test runs.")
    parser.add_argument("--seed-step", type=int, default=1, help="Seed increment between runs.")

    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--patience", type=int, default=10)
    parser.add_argument("--hidden-dim", type=int, default=128)
    parser.add_argument("--num-layers", type=int, default=2)
    parser.add_argument("--dropout", type=float, default=0.2)
    parser.add_argument("--bidirectional", action="store_true", help="Use bidirectional LSTM/GRU. Default is unidirectional.")
    parser.add_argument("--no-bidirectional", action="store_true", help=argparse.SUPPRESS)  # kept only for backward compatibility
    parser.add_argument("--tcn-levels", type=int, default=3)
    parser.add_argument("--tcn-kernel-size", type=int, default=3)
    parser.add_argument("--no-class-weight", dest="class_weight", action="store_false", help="Disable balanced class weights.")
    parser.set_defaults(class_weight=True)

    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", type=str, default=None, help="cuda, cpu, cuda:0, etc. Default auto.")
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument(
        "--temporal-order",
        choices=["ordered", "shuffled"],
        default="ordered",
        help="Use original ordering or independently shuffle time steps within each sequence.",
    )
    parser.add_argument(
        "--validation-only",
        action="store_true",
        help="Do not load or evaluate the test split.",
    )

    args = parser.parse_args()
    if args.runs < 1:
        raise ValueError("--runs must be at least 1")

    if args.suffix == "auto":
        suffix = auto_find_suffix(args.data_dir)
    else:
        suffix = args.suffix

    print(f"[*] Data dir: {args.data_dir}")
    print(f"[*] Using suffix: {suffix}")

    X_train, y_train_raw = load_split(args.data_dir, "train", suffix)
    X_val, y_val_raw = load_split(args.data_dir, "val", suffix)
    if args.validation_only:
        X_test, y_test_raw = None, None
    else:
        X_test, y_test_raw = load_split(args.data_dir, "test", suffix)

    label_arrays = [y_train_raw, y_val_raw]
    if y_test_raw is not None:
        label_arrays.append(y_test_raw)
    label_to_id, id_to_label = build_label_mapping(*label_arrays)
    labels = [id_to_label[i] for i in range(len(id_to_label))]

    y_train = encode_labels(y_train_raw, label_to_id)
    y_val = encode_labels(y_val_raw, label_to_id)
    y_test = None if y_test_raw is None else encode_labels(y_test_raw, label_to_id)

    print("\n[*] Loaded data:")
    print(f"    X_train: {X_train.shape}, y_train: {y_train.shape}")
    print(f"    X_val:   {X_val.shape}, y_val:   {y_val.shape}")
    if X_test is not None:
        print(f"    X_test:  {X_test.shape}, y_test:  {y_test.shape}")
    else:
        print("    X_test:  not loaded (--validation-only)")
    print("\n[*] Label mapping:")
    for i, label in enumerate(labels):
        print(f"    {i}: {label}")

    timestamp = time.strftime("%Y%m%d_%H%M%S")
    mode_suffix = f"{args.temporal_order}_{'valonly' if args.validation_only else 'full'}"
    run_dir = os.path.join(args.out_dir, f"{args.model}_{mode_suffix}_{suffix}_{timestamp}")
    ensure_dir(run_dir)

    with open(os.path.join(run_dir, f"{args.model}_label_mapping.json"), "w", encoding="utf-8") as f:
        json.dump({"label_to_id": label_to_id, "id_to_label": id_to_label}, f, ensure_ascii=False, indent=2)
    run_config = vars(args).copy()
    run_config["resolved_suffix"] = suffix
    with open(os.path.join(run_dir, f"{args.model}_run_config.json"), "w", encoding="utf-8") as f:
        json.dump(run_config, f, ensure_ascii=False, indent=2)

    model_names = ["lstm", "gru", "tcn"] if args.model == "all" else [args.model]

    summary_rows = []
    for run_idx in range(1, args.runs + 1):
        run_seed = int(args.seed + (run_idx - 1) * args.seed_step)
        for model_name in model_names:
            row = train_model(
                model_name,
                X_train,
                y_train,
                X_val,
                y_val,
                X_test,
                y_test,
                labels,
                args,
                run_dir,
                run_idx,
                run_seed,
            )
            summary_rows.append(row)

    summary_df = pd.DataFrame(summary_rows)
    summary_path = os.path.join(run_dir, f"{args.model}_all_runs_summary_metrics.csv")
    summary_df.to_csv(summary_path, index=False)
    aggregate_df = aggregate_runs(summary_df, run_dir)

    print("\n[完成] 时序 baseline 训练完成。")
    print(f"结果目录: {run_dir}")
    print(f"逐次结果: {summary_path}")
    print(f"均值标准差: {os.path.join(run_dir, f'{args.model}_aggregate_metrics_mean_std.csv')}")
    if args.runs > 1 and not args.validation_only:
        for model_name in model_names:
            row = aggregate_df[(aggregate_df["model"] == model_name) & (aggregate_df["metric"] == "test_macro_f1")].iloc[0]
            print(
                f"{model_name.upper()} test macro-F1 mean±std over {int(row['n'])} runs: "
                f"{row['mean']:.4f} ± {row['std']:.4f}"
            )


if __name__ == "__main__":
    main()
